export function getProductImage(
  productName: string,
  categoryName?: string,
  currentImage?: string | null,
): string {
  // Eğer görsel varsa ve geçerliyse (boş string değilse) onu kullan
  if (currentImage && currentImage.trim() !== '') return currentImage;

  const lowerName = productName.toLowerCase();

  // 1. İsim bazlı eşleştirme (PRODUCT_TEMPLATES)
  for (const [key, url] of Object.entries(PRODUCT_TEMPLATES)) {
    if (lowerName.includes(key)) return url;
  }

  // 2. Kategori bazlı eşleştirme
  if (categoryName) {
    const lowerCategory = categoryName.toLowerCase();
    for (const [key, url] of Object.entries(DEFAULT_CATEGORY_IMAGES)) {
      if (lowerCategory.includes(key)) return url;
    }
  }

  // 3. Varsayılan görsel
  return DEFAULT_CATEGORY_IMAGES['default'];
}
